import "server-only";
import { LocalStorage } from "./local";
import { NetlifyBlobsStorage } from "./netlify-blobs";
import { S3Storage } from "./s3";
import { VercelBlobStorage } from "./vercel-blob";

/**
 * Where original evidence files, document revisions and generated reports
 * live. Metadata stays in Postgres; only bytes go here.
 *
 *   STORAGE_DRIVER=local  (default) — files under STORAGE_DIR on the server's
 *                         disk, outside the web root, served only through
 *                         authenticated routes.
 *   STORAGE_DRIVER=s3     — any S3-compatible bucket (AWS S3, MinIO, Wasabi…).
 *   STORAGE_DRIVER=netlify-blobs — Netlify Blobs; chosen automatically when
 *                         running on Netlify Functions.
 *   STORAGE_DRIVER=vercel-blob — private Vercel Blob store; chosen
 *                         automatically on Vercel when BLOB_READ_WRITE_TOKEN is set.
 */
export interface FileStorage {
  readonly driver: string;
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  exists(key: string): Promise<boolean>;
  /** Only used for derived files (thumbnails, superseded report renders).
   *  Original evidence is never deleted by the application. */
  remove(key: string): Promise<void>;
}

let instance: FileStorage | null = null;

export function storage(): FileStorage {
  if (instance) return instance;
  const onNetlify = !!process.env.NETLIFY_BLOBS_CONTEXT || process.env.NETLIFY === "true";
  const onVercel = !!process.env.VERCEL && !!process.env.BLOB_READ_WRITE_TOKEN;
  const driver = (process.env.STORAGE_DRIVER ?? (onNetlify ? "netlify-blobs" : onVercel ? "vercel-blob" : "local")).toLowerCase();
  instance =
    driver === "s3"
      ? new S3Storage()
      : driver === "netlify-blobs"
        ? new NetlifyBlobsStorage()
        : driver === "vercel-blob"
          ? new VercelBlobStorage()
          : new LocalStorage(process.env.STORAGE_DIR ?? "./storage");
  return instance;
}

/** Keys are generated by the app, but validate anyway so a key can never
 *  escape the storage root. */
export function assertSafeKey(key: string) {
  if (!/^[a-zA-Z0-9][a-zA-Z0-9/_.-]*$/.test(key) || key.includes("..") || key.includes("//")) {
    throw new Error(`Unsafe storage key: ${key}`);
  }
}
