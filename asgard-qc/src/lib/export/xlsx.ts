interface Col {
  header: string;
  key: string;
  width?: number;
  /** Column holds a date. */
  date?: boolean;
  note?: string;
}

const NAVY = "FF0B1118";
const GOLD = "FFC39A45";

const d = (v: Date | null | undefined) => v ?? null;
const src = (isDemo: boolean) => (isDemo ? "DEMO" : "RECORD");

function addSheet(wb: ExcelJS.Workbook, name: string, cols: Col[], rows: Record<string, unknown>[]) {
  const ws = wb.addWorksheet(name, { views: [{ state: "frozen", ySplit: 1 }] });
  ws.columns = cols.map((c) => ({ header: c.header, key: c.key, width: c.width ?? Math.max(12, c.header.length + 4) }));
  const head = ws.getRow(1);
  head.font = { bold: true, color: { argb: "FFFFFFFF" } };
  head.fill = { type: "pattern", pattern: "solid", fgColor: { argb: NAVY } };
  head.alignment = { vertical: "middle" };
  head.height = 20;
  cols.forEach((c, i) => {
    if (c.note) head.getCell(i + 1).note = c.note;
    if (c.date) ws.getColumn(i + 1).numFmt = "yyyy-mm-dd hh:mm";
  });
  for (const r of rows) ws.addRow(r);
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: cols.length } };
  return ws;
}

function aboutSheet(wb: ExcelJS.Workbook, title: string, actor: Actor, filters: Record<string, unknown>, demoRows: number) {
  const ws = wb.addWorksheet("About", { properties: { tabColor: { argb: GOLD } } });
  ws.getColumn(1).width = 26;
  ws.getColumn(2).width = 90;
  ws.addRow(["ASGARD Modular Manufacturing — Quality Command Centre"]).font = { bold: true, size: 14 };
  ws.addRow([title]).font = { bold: true, size: 12, color: { argb: GOLD } };
  ws.addRow([]);
  ws.addRow(["Generated", new Date().toISOString()]);
  ws.addRow(["Generated by", `${actor.name} (${actor.role})`]);
  for (const [k, v] of Object.entries(filters)) ws.addRow([`Filter: ${k}`, v == null || v === "" ? "All" : String(v)]);
  ws.addRow(["Source column", "RECORD = entered in the application. DEMO = synthetic demonstration data, not a real quality record."]);
  if (demoRows) ws.addRow(["WARNING", `${demoRows} row(s) in this export are DEMO DATA.`]).font = { bold: true, color: { argb: "FFB9353A" } };
  ws.addRow(["Status", "Read-only extract. Editing this file does not change the source records."]);
  // Put About first: exceljs orders sheets by orderNo.
  const others = wb.worksheets.filter((w) => w !== ws);
  // orderNo is used by exceljs at runtime but missing from its typings.
  const order = (w: ExcelJS.Worksheet, n: number) => ((w as unknown as { orderNo: number }).orderNo = n);
  order(ws, 0);
  others.forEach((w, i) => order(w, i + 1));
}

